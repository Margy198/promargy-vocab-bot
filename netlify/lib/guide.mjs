const sectionOf = (key) => GUIDE_SECTIONS.find((s) => s.key === key) || null;

// Главное меню инструкции. done — ключи прочитанных разделов (отмечаем галочкой).
export function guideMenu(done = "") {
  const rows = GUIDE_SECTIONS.map((s) => [{ text: `${done.includes(s.key) ? "✅ " : ""}${s.button}`, callback_data: `g:${s.key}:0:${done}` }]);
  return { text: GUIDE_INTRO, reply_markup: { inline_keyboard: rows } };
}

// Карточка раздела: «Раздел · 2 из 5», заголовок, текст и кнопки «Назад / Дальше / Разделы».
export function guideCard(key, page, done = "") {
  const s = sectionOf(key); if (!s) return guideMenu(done);
  const i = Math.max(0, Math.min(s.cards.length - 1, Number(page) || 0)); const c = s.cards[i]; const last = i === s.cards.length - 1;
  const doneNext = last && !done.includes(key) ? done + key : done;
  const nav = [];
  if (i > 0) nav.push({ text: "← Назад", callback_data: `g:${key}:${i - 1}:${done}` });
  if (!last) nav.push({ text: "Дальше →", callback_data: `g:${key}:${i + 1}:${done}` });
  const rows = [nav];
  if (last) {
    const next = GUIDE_SECTIONS.find((x) => x.key !== key && !doneNext.includes(x.key));
    if (next) rows.push([{ text: `Дальше: ${next.button} →`, callback_data: `g:${next.key}:0:${doneNext}` }]);
  }
  rows.push([{ text: "☰ Все разделы", callback_data: `g:menu:0:${last ? doneNext : done}` }]);
  return { text: `${s.title} · ${i + 1} из ${s.cards.length}\n\n${c.t.toUpperCase()}\n\n${c.x}`, reply_markup: { inline_keyboard: rows.filter((r) => r.length) } };
}

// Разбор callback_data «g:<раздел|menu>:<страница>:<прочитанные>»
export function guideFromCallback(data) {
  const m = String(data || "").match(/^g:(menu|[a-z]):(\d{1,2}):([a-z]{0,6})$/); if (!m) return null;
  return m[1] === "menu" ? guideMenu(m[3]) : guideCard(m[1], Number(m[2]), m[3]);
}

