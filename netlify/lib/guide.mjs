// Разбор нажатий в помощи: «f:menu», «f:<номер>», «h:menu». «h:cmds» обрабатывает бот (там его список команд).
export function helpFromCallback(data) {
  const d = String(data || "");
  if (d === "h:menu") return helpMenu();
  if (d === "f:menu") return faqMenu();
  const m = d.match(/^f:(\d{1,2})$/); if (m) return faqAnswer(m[1]);
  return null;
}
