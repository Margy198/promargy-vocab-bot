// Инструкция для ученика «в три кнопки» (Лексика, Грамматика, Организационное), помощь и частые вопросы.
// Каждый раздел — несколько коротких карточек с кнопкой «Дальше»: одна мысль на экран, а не простыня.
// Правило Маргариты: в инструкции только то, что реально есть в боте и приложении; без буквы «е» с точками.
//
// Обращение и род подставляются по настройкам ученика:
//   {ты|вы}           — два варианта: на «ты» и на «вы»;
//   {он|она|вы}       — три варианта: на «ты» мужчине, на «ты» женщине, на «вы».
// who = { formal: true|false, gender: "m"|"f"|null }.

export function say(text, who = {}) {
  return String(text).replace(/\{([^{}]*)\}/g, (all, body) => {
    const p = body.split("|");
    if (p.length === 2) return who.formal ? p[1] : p[0];
    if (p.length === 3) return who.formal ? p[2] : who.gender === "f" ? p[1] : p[0];
    return all;
  });
}

